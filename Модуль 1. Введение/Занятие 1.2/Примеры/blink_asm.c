// Мигание встроенным светодиодом Raspberry Pi Pico с ассемблерными вставками.
//
// Настройку вывода выполняет Pico SDK, а переключение светодиода и задержку —
// отдельные команды процессора Cortex-M0+, вписанные прямо в код на C.
//
// Пример к теории т1.2.4 «Внутреннее устройство. Процессор».

#include "pico/stdlib.h"
#include "hardware/regs/sio.h"        // смещения регистров блока SIO
#include "hardware/regs/addressmap.h" // базовые адреса, в т. ч. SIO_BASE

#define LED_PIN 25                     // встроенный светодиод Pico — на GPIO25

int main() {
    // Настройку вывода оставим за SDK: перевести GPIO25 в режим выхода
    gpio_init(LED_PIN);
    gpio_set_dir(LED_PIN, GPIO_OUT);

    const uint32_t led_mask = 1u << LED_PIN;   // 25-й бит соответствует выводу
    // Адрес регистра, инвертирующего состояние выводов (0xd000001c)
    volatile uint32_t *gpio_xor =
        (uint32_t *)(SIO_BASE + SIO_GPIO_OUT_XOR_OFFSET);

    while (true) {
        // Переключить светодиод одной командой записи в память
        asm volatile (
            "str %[mask], [%[reg]]"    // STR: записать число из регистра в память
            :                          // выходных операндов нет
            : [mask] "r" (led_mask),   // %[mask] — регистр с маской
              [reg]  "r" (gpio_xor)    // %[reg]  — регистр с адресом
            : "memory"
        );

        // Задержка: пустой цикл на несколько миллионов команд
        uint32_t count = 20000000;
        asm volatile (
            "1:\n"                     // локальная метка «1»
            "   subs %[c], %[c], #1\n" // SUBS: c = c - 1 и выставить флаги
            "   bne  1b\n"             // BNE: пока c != 0 — прыгать назад к метке 1
            : [c] "+r" (count)         // c одновременно читается и изменяется
            :
            : "cc"                     // команда меняет флаги процессора
        );
    }
}
